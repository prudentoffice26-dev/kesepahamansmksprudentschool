// Render List Cards di Frame 6
function renderBabCards(dataList) {
  babCardList.innerHTML = "";

  if (dataList.length === 0) {
    babCardList.innerHTML = `
      <div class="text-center py-8 text-slate-400 text-xs font-medium">
        Data tidak ditemukan. Coba kata kunci lain.
      </div>
    `;
    return;
  }

  dataList.forEach((item) => {
    const card = document.createElement("div");
    card.className = "bg-white p-4 rounded-2xl border border-slate-100 shadow-sm hover:border-prudent-teal transition-all btn-press cursor-pointer";
    
    card.innerHTML = `
      <div class="space-y-1.5">
        <h3 class="font-extrabold text-prudent-blue text-sm md:text-base tracking-tight uppercase">${item.title}</h3>
        <p class="text-xs text-slate-500 line-clamp-3 leading-relaxed font-normal">${item.deskripsi}</p>
      </div>
    `;

    card.addEventListener("click", () => {
      openBabDetail(item);
    });

    babCardList.appendChild(card);
  });
}

