window.addEventListener("resize", () => {
  if (window.innerWidth >= 768) {
    if (!activeBabId) activeBabId = 1;
    renderSidebarNav();
    babListSection.classList.remove("hidden");
    babDetailSection.classList.remove("hidden");
    mobileBackBtn.classList.add("hidden");
  }
});

