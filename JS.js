// LOGIKA DARK MODE
function initDarkMode() {
  const darkModeToggle = document.getElementById("darkModeToggle");
  const mediaQuery = window.matchMedia("(prefers-color-scheme: dark)");

  function applyTheme(isDark) {
    if (isDark) {
      document.documentElement.classList.add("dark");
    } else {
      document.documentElement.classList.remove("dark");
    }
  }

  applyTheme(mediaQuery.matches);

  mediaQuery.addEventListener("change", (e) => {
    applyTheme(e.matches);
  });

  if (darkModeToggle) {
    darkModeToggle.addEventListener("click", () => {
      document.documentElement.classList.toggle("dark");
    });
  }
}

// TAMPILKAN DAFTAR BAB SEBAGAI HALAMAN UTAMA DI MOBILE (RESET HIGHLIGHT HIJAU)
function showMobileList() {
  if (window.innerWidth < 768) {
    activeBabId = null; // Clear bab aktif agar tombol kembali normal
    renderSidebarNav();
    babListSection.classList.remove("hidden");
    babDetailSection.classList.add("hidden");
    mobileBackBtn.classList.add("hidden");
    mobileBackBtn.classList.remove("flex");
  } else {
    if (!activeBabId) activeBabId = 1;
    renderSidebarNav();
    babListSection.classList.remove("hidden");
    babDetailSection.classList.remove("hidden");
    mobileBackBtn.classList.add("hidden");
  }
  window.scrollTo({ top: 0, behavior: "smooth" });
}

// FUNGSI UTAMA PILIH BAB
function selectBab(babId, isMobileClick = true) {
  activeBabId = babId;
  const currentBab = kesepahamanData.find(item => item.id === babId);
  if (!currentBab) return;

  if (activeBabBadge) activeBabBadge.textContent = currentBab.babLabel;
  if (activeBabTitle) activeBabTitle.textContent = currentBab.title;
  if (activeBabDeskripsi) activeBabDeskripsi.textContent = currentBab.deskripsi;

  renderSidebarNav();
  renderPasalContent(currentBab);

  if (window.innerWidth < 768 && isMobileClick) {
    babListSection.classList.add("hidden");
    babDetailSection.classList.remove("hidden");
    mobileBackBtn.classList.remove("hidden");
    mobileBackBtn.classList.add("flex");
  }

  window.scrollTo({ top: 0, behavior: "smooth" });
}

// RENDER SIDEBAR NAVIGASI
function renderSidebarNav() {
  if (!sidebarList) return;

  sidebarList.innerHTML = "";
  kesepahamanData.forEach((item) => {
    const isActive = item.id === activeBabId;
    const btn = document.createElement("button");
    btn.type = "button";
    
    const baseClass = "w-full text-left px-4 py-3 rounded-xl text-xs transition-all btn-press ";
    const activeClass = "bg-prudent-teal text-white dark:bg-prudent-tealNeon dark:text-slate-900 font-extrabold shadow-sm";
    const inactiveClass = "text-slate-700 dark:text-slate-200 font-bold hover:bg-slate-100 dark:hover:bg-slate-800/60 hover:text-prudent-teal dark:hover:text-prudent-tealNeon";

    btn.className = baseClass + (isActive ? activeClass : inactiveClass);
    btn.innerHTML = `<span class="truncate tracking-wide block">${item.babLabel}</span>`;

    btn.addEventListener("click", () => {
      selectBab(item.id, true);
    });

    sidebarList.appendChild(btn);
  });
}

