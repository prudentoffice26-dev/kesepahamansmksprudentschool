// LOGIKA PENCARIAN DOKUMEN
function setupSearch() {
  if (!searchInput) return;

  searchInput.addEventListener("input", (e) => {
    const query = e.target.value.toLowerCase().trim();
    
    if (query) {
      if (clearSearchBtn) clearSearchBtn.classList.remove("hidden");
    } else {
      if (clearSearchBtn) clearSearchBtn.classList.add("hidden");
      if (window.innerWidth < 768) {
        showMobileList();
      } else {
        selectBab(activeBabId || 1, false);
      }
      return;
    }

    const matchedBab = kesepahamanData.find((item) => {
      const matchTitle = item.title.toLowerCase().includes(query);
      const matchBab = item.babLabel.toLowerCase().includes(query);
      const matchPasal = item.pasalList && item.pasalList.some(p => 
        p.nomor.toLowerCase().includes(query) ||
        p.judul.toLowerCase().includes(query)
      );
      return matchTitle || matchBab || matchPasal;
    });

    if (matchedBab) {
      selectBab(matchedBab.id, true);
    }
  });

  if (clearSearchBtn) {
    clearSearchBtn.addEventListener("click", () => {
      searchInput.value = "";
      clearSearchBtn.classList.add("hidden");
      if (window.innerWidth < 768) {
        showMobileList();
      } else {
        selectBab(activeBabId || 1, false);
      }
      searchInput.focus();
    });
  }
}

